// Maintenance generator: bundles the trust lists into src/trust/*.ts. Run before a
// release (`npm run gen:trust-lists`); the bridge never fetches trust lists at runtime.
//
//  - official: the C2PA Trust List and C2PA TSA Trust List from c2pa-org/conformance-public
//    (the JSON variant only supplies issue date, sequence number and NextUpdate).
//  - interim:  the frozen CAI interim list served by verify.contentauthenticity.org/trust/.
import { writeFileSync } from 'node:fs'

const OFFICIAL = 'https://raw.githubusercontent.com/c2pa-org/conformance-public/main/trust-list'
const INTERIM = 'https://verify.contentauthenticity.org/trust'

async function text (url) {
    const res = await fetch(url)
    if (!res.ok) throw new Error(`${res.status} ${url}`)
    const body = await res.text()
    if (body.trimStart().startsWith('<')) throw new Error(`HTML instead of a trust resource: ${url}`)
    return body.replace(/\r\n/g, '\n')
}

async function listInfo (name) {
    const json = JSON.parse(await text(`${OFFICIAL}/${name}.json`))
    const info = json.LoTE.ListAndSchemeInformation
    return { issued: info.ListIssueDateTime, sequence: info.LoTESequenceNumber, nextUpdate: info.NextUpdate }
}

const literal = s => JSON.stringify(s)
const header = (what, source) => `/**
 * @copyright
 * (c) 2026 netTrek GmbH & Co. KG
 *
 * GENERATED by scripts/gen-trust-lists.mjs — do not edit. ${what}
 * Source: ${source}
 */
`

const [signer, tsa, signerInfo, tsaInfo] = await Promise.all([
    text(`${OFFICIAL}/C2PA-TRUST-LIST.pem`),
    text(`${OFFICIAL}/C2PA-TSA-TRUST-LIST.pem`),
    listInfo('C2PA-TRUST-LIST'),
    listInfo('C2PA-TSA-TRUST-LIST')
])
writeFileSync('src/trust/official.ts', `${header('The official C2PA Trust List and C2PA TSA Trust List.', `${OFFICIAL}/`)}
export const C2PA_TRUST_LIST = ${literal(signer)}

export const C2PA_TSA_TRUST_LIST = ${literal(tsa)}

/** List metadata; \`nextUpdate\` is when C2PA announces the next issue. */
export const C2PA_TRUST_LIST_INFO = ${literal(signerInfo)}
export const C2PA_TSA_TRUST_LIST_INFO = ${literal(tsaInfo)}
`)

const [anchors, allowedList, trustConfig] = await Promise.all(
    ['anchors.pem', 'allowed.sha256.txt', 'store.cfg'].map(f => text(`${INTERIM}/${f}`))
)
writeFileSync('src/trust/interim.ts', `${header('The frozen CAI interim trust list (signer + TSA anchors, allow-list, EKU config).', `${INTERIM}/`)}
export const INTERIM_TRUST_ANCHORS = ${literal(anchors)}

export const INTERIM_ALLOWED_LIST = ${literal(allowedList)}

export const INTERIM_TRUST_CONFIG = ${literal(trustConfig)}
`)

const count = pem => (pem.match(/BEGIN CERTIFICATE/g) ?? []).length
console.log(`official: ${count(signer)} signer + ${count(tsa)} TSA anchors (next update ${signerInfo.nextUpdate} / ${tsaInfo.nextUpdate})`)
console.log(`interim:  ${count(anchors)} anchors, ${allowedList.split('\n').filter(l => l && !l.startsWith('#')).length} allow-listed certs`)
